#!/usr/bin/env python3
"""Generate charts/mcp-tool/values.schema.json from schemas/tool-manifest.schema.json.

The chart's values are the tool manifest itself (so `helm template x charts/mcp-tool -f
tools/x/manifest.yaml` works and Argo CD can pass the manifest as a values file) plus a
`platform` block supplied by platform/values/<profile>.yaml. Keeping one source for the manifest
shape means the chart cannot accept a manifest the validator would reject.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "schemas" / "tool-manifest.schema.json"
DST = ROOT / "charts" / "mcp-tool" / "values.schema.json"

PLATFORM = {
    "type": "object",
    "description": "Platform wiring supplied by platform/values/<profile>.yaml, never by a tool manifest.",
    "required": ["gateway", "adapter", "keycloak", "secrets", "kmcp", "networkPolicy", "podSecurity"],
    "properties": {
        "profile": {"enum": ["laptop", "cloud-gpu"]},
        "namespaceOverride": {"type": "string"},
        "gateway": {
            "type": "object",
            "required": ["name", "namespace", "publicUrl"],
            "properties": {
                "name": {"type": "string"},
                "namespace": {"type": "string"},
                "publicUrl": {"type": "string", "pattern": "^https?://"},
            },
        },
        "adapter": {
            "type": "object",
            "required": ["name", "namespace", "grpcPort"],
            "properties": {
                "name": {"type": "string"},
                "namespace": {"type": "string"},
                "grpcPort": {"type": "integer"},
                "httpPort": {"type": "integer"},
            },
        },
        "keycloak": {
            "type": "object",
            "required": ["issuer", "serviceName", "namespace", "port", "realm", "mcpAudience", "jwksPath", "tokenPath", "gatewayClientId", "gatewayClientSecretName", "gatewayClientSecretPath"],
            "properties": {
                "issuer": {"type": "string", "pattern": "^https?://"},
                "serviceName": {"type": "string"},
                "namespace": {"type": "string"},
                "port": {"type": "integer"},
                "realm": {"type": "string"},
                "mcpAudience": {"type": "string"},
                "jwksPath": {"type": "string", "pattern": "^/"},
                "tokenPath": {"type": "string", "pattern": "^/"},
                "gatewayClientId": {"type": "string"},
                "gatewayClientSecretName": {"type": "string"},
                "gatewayClientSecretPath": {"type": "string"},
            },
        },
        "secrets": {
            "type": "object",
            "required": ["clusterSecretStore"],
            "properties": {"clusterSecretStore": {"type": "string"}},
        },
        "kmcp": {
            "type": "object",
            "required": ["port", "path", "podLabelKey"],
            "properties": {
                "port": {"type": "integer"},
                "path": {"type": "string", "pattern": "^/"},
                "podLabelKey": {"type": "string"},
                "adapterImage": {"type": "string"},
            },
        },
        "networkPolicy": {
            "type": "object",
            "required": ["fqdn"],
            "properties": {"fqdn": {"enum": ["none", "cilium"]}},
        },
        "podSecurity": {
            "type": "object",
            "required": ["runAsUser"],
            "properties": {"runAsUser": {"type": "integer", "minimum": 1000}},
        },
    },
}


def main() -> None:
    src = json.loads(SRC.read_text())
    out = dict(src)
    out["$id"] = "https://eacp.dev/schemas/v1alpha1/mcp-tool-chart-values.schema.json"
    out["title"] = "mcp-tool chart values"
    out["description"] = "GENERATED by scripts/sync-chart-schema.py from schemas/tool-manifest.schema.json plus the platform block. Do not edit."
    out["required"] = list(src["required"]) + ["platform"]
    out["properties"] = dict(src["properties"])
    out["properties"]["platform"] = PLATFORM
    DST.write_text(json.dumps(out, indent=2) + "\n")
    print(f"wrote {DST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
